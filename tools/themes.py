#!/usr/bin/env python3
"""One theme list for the suite. The editor's table in hake.c is the source;
this writes the agent's copy (the THEMES block in ../hako-code/hako.c — inside
the file, because the studio's build fetches hako.c alone) and the studio's (the
THEMES block in ../hako-studio/index.html) from it.

    python3 tools/themes.py           write both
    python3 tools/themes.py --check   exit 1 if either copy has drifted

The editor has 12 colours per theme, painted on its own background. The agent
prints onto the TERMINAL's background and needs 9 text colours; the studio
paints its own page and needs 13. Both are derived here, so a theme added to
hake.c reaches all three. mithraeum and nord keep their hand-tuned values."""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
HAKE = os.path.join(HERE, "..", "hake.c")
AGENT = os.path.join(HERE, "..", "..", "hako-code", "hako.c")
STUDIO = os.path.join(HERE, "..", "..", "hako-studio", "index.html")
SLOTS = ["bg", "fg", "comment", "keyword1", "keyword2", "string", "line_number",
         "status_bg", "status_fg", "border", "visual_bg", "visual_fg"]

# The two that existed everywhere before the lists were joined: keep their look.
AGENT_TUNED = {
    # the suite's inks on a dark terminal: legibility first (>= 5:1 on black)
    "mithraeum": ["0x8d99ff", "0xe8e2d2", "0x9a9383", "HK_C_BOLDRED", "0xd6c496", "0x8d99ff", "0x8d99ff", "0x8a8473", "0x5f5a4e"],
    "nord":      ["0x8fbcbb", "0xe5e9f0", "0x6c788d", "HK_C_BOLDRED", "0xd08770", "0xa3be8c", "0x88c0d0", "0x646e80", "0x4c566a"],
}
STUDIO_TUNED = {
    # the suite's look on a dark ground, and on paper
    "mithraeum": dict(bg='#14130f', panel='#1b1a16', **{'panel-2': '#23211c'}, line='#2e2b24', **{'line-2': '#3c382f'},
                      bone='#e8e2d2', gold='#8d99ff', **{'gold-dim': '#5d68c2'}, phos='#d6c496',
                      dim='#8a8473', faint='#5f5a4e', err='#ff5a4a', ink='#14130f'),
    "washi":     dict(bg='#ece7da', panel='#e4dece', **{'panel-2': '#dad3c1'}, line='#cfc7b3', **{'line-2': '#b9b09a'},
                      bone='#1d1c19', gold='#2636c4', **{'gold-dim': '#6a76c9'}, phos='#6b4a2b',
                      dim='#5f5a4e', faint='#8a8473', err='#c2311f', ink='#ece7da'),
    "nord":      dict(bg='#2e3440', panel='#333b49', **{'panel-2': '#3b4252'}, line='#434c5e', **{'line-2': '#4c566a'},
                      bone='#e5e9f0', gold='#88c0d0', **{'gold-dim': '#5e81ac'}, phos='#a3be8c',
                      dim='#8794a8', faint='#667487', err='#bf616a', ink='#2e3440'),
}
STUDIO_KEYS = ["bg", "panel", "panel-2", "line", "line-2", "bone", "gold", "gold-dim",
               "phos", "dim", "faint", "err", "ink"]

def read_themes():
    src = open(HAKE).read()
    block = src[src.index("HK_THEMES[] = {"):]
    block = block[:block.index("\n};")]
    out = []
    for line in block.splitlines():
        m = re.match(r'\s*\{"([a-z0-9-]+)",', line)
        if not m: continue
        rgb = [tuple(int(x) for x in t) for t in re.findall(r'\{(\d+),\s*(\d+),\s*(\d+)\}', line)]
        assert len(rgb) == 12, (m.group(1), len(rgb))
        out.append((m.group(1), dict(zip(SLOTS, rgb))))
    assert out, "no themes found in hake.c"
    return out

def hexc(c): return "0x%02x%02x%02x" % c
def css(c): return "#%02x%02x%02x" % c
def mix(a, b, t): return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))
def light(c): return (c[0] * 299 + c[1] * 587 + c[2] * 114) / 1000 > 128

def agent_row(name, t):
    if name in AGENT_TUNED: return AGENT_TUNED[name]
    # A light theme's text is dark: on a dark terminal it would vanish. Body text
    # then stays in the terminal's own colour; the accents still carry the theme.
    ai = "HK_C_NONE" if light(t["bg"]) else hexc(t["fg"])
    return [hexc(t["keyword2"]), ai, hexc(t["comment"]), "HK_C_BOLDRED", hexc(t["string"]),
            hexc(greenest(t)), hexc(t["keyword1"]), hexc(t["comment"]), hexc(t["line_number"])]

def greenest(t):
    """Success reads as green: the theme's greenest colour, not whatever strings are."""
    cands = [t[k] for k in ("string", "keyword2", "keyword1", "comment")]
    return max(cands, key=lambda c: c[1] - max(c[0], c[2]))

def studio_row(name, t):
    if name in STUDIO_TUNED: return STUDIO_TUNED[name]
    bg, fg, acc = t["bg"], t["fg"], t["keyword1"]
    return {"bg": css(bg), "panel": css(mix(bg, fg, .04)), "panel-2": css(mix(bg, fg, .08)),
            "line": css(mix(bg, fg, .15)), "line-2": css(mix(bg, fg, .22)), "bone": css(fg),
            "gold": css(acc), "gold-dim": css(mix(acc, bg, .35)), "phos": css(greenest(t)),
            "dim": css(t["comment"]), "faint": css(t["line_number"]),
            "err": "#d0564a" if not light(bg) else "#b3261e", "ink": css(bg)}

def agent_text(themes):
    w = max(len(n) for n, _ in themes) + 3
    lines = ["/* THEMES:BEGIN — generated by hako-edit/tools/themes.py from hake.c; do not edit */"]
    for n, t in themes:
        lines.append('\t{%-*s {%s}},' % (w, '"%s",' % n, ", ".join(agent_row(n, t))))
    lines.append("/* THEMES:END */")
    return "\n".join(lines)

def agent_splice(src, block):
    a = src.index("/* THEMES:BEGIN")
    b = src.index("/* THEMES:END */", a) + len("/* THEMES:END */")
    return src[:a] + block + src[b:]

def studio_text(themes):
    rows = []
    for n, t in themes:
        r = studio_row(n, t)
        body = ", ".join("%s:'%s'" % (k if "-" not in k else "'%s'" % k, r[k]) for k in STUDIO_KEYS)
        rows.append("\t%s: { %s }" % (n if "-" not in n else "'%s'" % n, body))
    return ("/* THEMES:BEGIN — generated by hako-edit/tools/themes.py from hake.c; do not edit */\n"
            "const THEMES = {\n" + ",\n".join(rows) + "\n};\n/* THEMES:END */")

def studio_splice(html, block):
    a = html.index("/* THEMES:BEGIN") if "/* THEMES:BEGIN" in html else html.index("const THEMES = {")
    end_marker = "/* THEMES:END */"
    b = html.index(end_marker, a) + len(end_marker) if end_marker in html[a:] else html.index("\n};", a) + 3
    return html[:a] + block + html[b:]

def main():
    check = "--check" in sys.argv
    themes = read_themes()
    want_agent = agent_text(themes)
    drift = []
    if os.path.exists(AGENT):
        src = open(AGENT).read()
        new = agent_splice(src, want_agent)
        if new != src:
            drift.append(AGENT)
            if not check: open(AGENT, "w").write(new)
    if os.path.exists(STUDIO):
        html = open(STUDIO).read()
        new = studio_splice(html, studio_text(themes))
        if new != html:
            drift.append(STUDIO)
            if not check: open(STUDIO, "w").write(new)
    if check:
        for d in drift: print("themes: out of step with hake.c:", os.path.relpath(d, HERE + "/.."))
        print("themes: %d in hake.c, copies %s" % (len(themes), "DRIFTED" if drift else "in step"))
        sys.exit(1 if drift else 0)
    print("themes: %d from hake.c -> %s" % (len(themes), ", ".join(os.path.relpath(d, HERE + "/..") for d in drift) or "nothing changed"))

if __name__ == "__main__":
    main()
